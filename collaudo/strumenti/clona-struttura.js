// Ricostruisce nel database di COLLAUDO la struttura dello schema «public» della
// produzione, a partire dalla descrizione prodotta da struttura.js, e poi
// confronta le due descrizioni.
//
//   node clona-struttura.js ddl        -> scrive baseline.sql (solo generazione)
//   node clona-struttura.js applica    -> genera e applica al collaudo
//   node clona-struttura.js confronta  -> confronta produzione e collaudo
const fs = require('fs');
const path = require('path');
const { collaudo, produzione } = require('./sb.js');
const { descrivi } = require('./struttura.js');

const QUI = __dirname;
const RUOLI_API = ['PUBLIC', 'anon', 'authenticated', 'service_role'];
const id = (s) => '"' + String(s).replace(/"/g, '""') + '"';
const tab = (t) => 'public.' + id(t);
const ruolo = (r) => (r === 'PUBLIC' || r === 'public' ? 'PUBLIC' : id(r));
const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const CMD = { '*': 'all', r: 'select', a: 'insert', w: 'update', d: 'delete' };

function generaDDL(d) {
  const out = [];
  const riga = (s) => out.push(s);
  riga('-- Baseline del collaudo: struttura dello schema public identica alla produzione.');
  riga('-- Generata da clona-struttura.js: non modificare a mano.');
  riga('');

  riga('-- 1. Sequenze');
  for (const s of d.sequenze.filter((x) => !x.interna_identity)) {
    riga(`create sequence ${tab(s.sequenza)} as ${s.tipo} increment by ${s.passo} minvalue ${s.min} maxvalue ${s.max} start with ${s.inizio} cache ${s.cache} ${s.ciclo ? 'cycle' : 'no cycle'};`);
  }

  riga('');
  riga('-- 2. Tabelle');
  for (const t of d.tabelle) {
    const cols = d.colonne.filter((c) => c.tabella === t.tabella).sort((a, b) => a.pos - b.pos).map((c) => {
      let s = '  ' + id(c.colonna) + ' ' + c.tipo;
      if (c.collazione) s += ' collate ' + id(c.collazione);
      if (c.generata === 's') s += ' generated always as (' + c.default + ') stored';
      else if (c.default) s += ' default ' + c.default;
      if (c.identity === 'a') s += ' generated always as identity';
      if (c.identity === 'd') s += ' generated by default as identity';
      if (c.not_null) s += ' not null';
      return s;
    });
    riga(`create table ${tab(t.tabella)} (\n${cols.join(',\n')}\n)${t.opzioni ? ' with (' + t.opzioni + ')' : ''};`);
  }

  riga('');
  riga('-- 3. Proprietà delle sequenze');
  for (const s of d.sequenze.filter((x) => !x.interna_identity && x.di)) {
    const [t, c] = s.di.split('.');
    riga(`alter sequence ${tab(s.sequenza)} owned by ${tab(t)}.${id(c)};`);
  }

  riga('');
  riga('-- 4. Vincoli (chiavi primarie, univoci e check prima delle chiavi esterne)');
  const ordineTipo = (k) => (k.tipo === 'f' ? 1 : 0);
  for (const k of [...d.vincoli].sort((a, b) => ordineTipo(a) - ordineTipo(b))) {
    riga(`alter table ${tab(k.tabella)} add constraint ${id(k.vincolo)} ${k.definizione};`);
  }

  riga('');
  riga('-- 5. Indici non legati a un vincolo');
  for (const i of d.indici.filter((x) => !x.da_vincolo)) riga(i.definizione + ';');

  riga('');
  riga('-- 6. Funzioni');
  for (const f of d.funzioni) riga(f.definizione.trim() + ';');

  riga('');
  riga('-- 7. Trigger');
  for (const t of d.trigger) {
    riga(t.definizione + ';');
    if (t.stato !== 'O') riga(`alter table ${tab(t.tabella)} disable trigger ${id(t.trigger)};`);
  }

  riga('');
  riga('-- 8. Row Level Security');
  for (const t of d.tabelle) {
    riga(`alter table ${tab(t.tabella)} ${t.rls ? 'enable' : 'disable'} row level security;`);
    if (t.rls_forzata) riga(`alter table ${tab(t.tabella)} force row level security;`);
  }
  for (const p of d.policy) {
    let s = `create policy ${id(p.policy)} on ${tab(p.tabella)} as ${p.permissiva ? 'permissive' : 'restrictive'} for ${CMD[p.comando]} to ${p.ruoli.map(ruolo).join(', ')}`;
    if (p.using) s += ` using (${p.using})`;
    if (p.check) s += ` with check (${p.check})`;
    riga(s + ';');
  }

  riga('');
  riga('-- 9. Privilegi: si azzera ciò che il progetto concede in automatico e si');
  riga('--    rimette esattamente ciò che ha la produzione.');
  const concedi = (oggetto, elenco, chiave) => {
    for (const g of elenco) {
      const semplici = g.privilegi.split(',').filter((x) => !x.endsWith('*'));
      const conOpzione = g.privilegi.split(',').filter((x) => x.endsWith('*')).map((x) => x.slice(0, -1));
      if (semplici.length) riga(`grant ${semplici.join(', ')} on ${oggetto(g[chiave])} to ${ruolo(g.ruolo)};`);
      if (conOpzione.length) riga(`grant ${conOpzione.join(', ')} on ${oggetto(g[chiave])} to ${ruolo(g.ruolo)} with grant option;`);
    }
  };
  // Le tabelle senza alcuna riga di privilegio in produzione vanno azzerate lo stesso.
  for (const t of d.tabelle) riga(`revoke all on table ${tab(t.tabella)} from ${RUOLI_API.map(ruolo).join(', ')};`);
  concedi((n) => 'table ' + tab(n), d.privilegi_tabelle, 'tabella');
  for (const g of d.privilegi_colonne) riga(`grant ${g.privilegio} (${id(g.colonna)}) on table ${tab(g.tabella)} to ${ruolo(g.ruolo)};`);
  for (const s of d.sequenze) riga(`revoke all on sequence ${tab(s.sequenza)} from ${RUOLI_API.map(ruolo).join(', ')};`);
  concedi((n) => 'sequence ' + tab(n), d.privilegi_sequenze, 'sequenza');
  for (const f of d.funzioni) riga(`revoke all on function public.${id(f.funzione)}(${f.argomenti}) from ${RUOLI_API.map(ruolo).join(', ')};`);
  for (const g of d.privilegi_funzioni) {
    const m = /^(.*?)\((.*)\)$/.exec(g.funzione);
    riga(`grant ${g.privilegi.replace(/\*/g, '')} on function public.${id(m[1])}(${m[2]}) to ${ruolo(g.ruolo)};`);
  }

  riga('');
  riga('-- 10. Realtime');
  for (const t of d.tabelle) {
    if (t.replica_identity === 'f') riga(`alter table ${tab(t.tabella)} replica identity full;`);
    if (t.replica_identity === 'n') riga(`alter table ${tab(t.tabella)} replica identity nothing;`);
    if (t.replica_identity === 'i') throw new Error('replica identity su indice non gestita: ' + t.tabella);
  }
  for (const p of d.pubblicazione) {
    riga(`alter publication ${id(p.pubblicazione)} add table ${tab(p.tabella)}${p.colonne ? ' (' + p.colonne.split(',').map(id).join(', ') + ')' : ''}${p.filtro ? ' where (' + p.filtro + ')' : ''};`);
  }

  riga('');
  riga('-- 11. Commenti');
  for (const t of d.tabelle.filter((x) => x.commento)) riga(`comment on table ${tab(t.tabella)} is ${lit(t.commento)};`);
  for (const c of d.colonne.filter((x) => x.commento)) riga(`comment on column ${tab(c.tabella)}.${id(c.colonna)} is ${lit(c.commento)};`);

  return out.join('\n') + '\n';
}

// Differenze ammesse: ciò che il progetto di collaudo ha in più per scelta —
// la RLS automatica attivata alla creazione del progetto e la tabella
// posta_simulata, dove il finto Google registra le mail invece di spedirle.
const SOLO_COLLAUDO = 'posta_simulata';
function ripulisci(d) {
  const c = JSON.parse(JSON.stringify(d));
  c.funzioni = c.funzioni.filter((f) => f.funzione !== 'rls_auto_enable');
  c.privilegi_funzioni = c.privilegi_funzioni.filter((f) => !f.funzione.startsWith('rls_auto_enable('));
  for (const blocco of Object.keys(c)) {
    if (!Array.isArray(c[blocco])) continue;
    c[blocco] = c[blocco].filter((x) => x.tabella !== SOLO_COLLAUDO && !String(x.sequenza || '').startsWith(SOLO_COLLAUDO + '_'));
  }
  return c;
}

function differenze(a, b) {
  const diff = [];
  for (const blocco of Object.keys(a)) {
    const A = a[blocco], B = b[blocco];
    if (!Array.isArray(A)) { if (JSON.stringify(A) !== JSON.stringify(B)) diff.push(blocco + ': ' + JSON.stringify(A) + ' ≠ ' + JSON.stringify(B)); continue; }
    const sa = new Set(A.map((x) => JSON.stringify(x))), sb = new Set(B.map((x) => JSON.stringify(x)));
    for (const x of sa) if (!sb.has(x)) diff.push(blocco + ' — solo in PRODUZIONE: ' + x.slice(0, 260));
    for (const x of sb) if (!sa.has(x)) diff.push(blocco + ' — solo in COLLAUDO:   ' + x.slice(0, 260));
  }
  return diff;
}

async function main() {
  const cmd = process.argv[2];
  const p = produzione();
  const dProd = await descrivi(p.leggi);
  fs.writeFileSync(path.join(QUI, 'struttura-produzione.json'), JSON.stringify(dProd, null, 1));

  if (cmd === 'ddl' || cmd === 'applica') {
    const ddl = generaDDL(dProd);
    fs.writeFileSync(path.join(QUI, '..', 'baseline.sql'), ddl);
    console.log('baseline.sql: ' + ddl.split('\n').length + ' righe, ' + ddl.length + ' caratteri');
    if (cmd === 'ddl') return;
    const c = collaudo();
    const gia = await c.query("select count(*)::int as n from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind = 'r'");
    if (gia[0].n > 0) throw new Error('il collaudo contiene già ' + gia[0].n + ' tabelle: baseline non applicata');
    const r = await c.api('POST', '/database/migrations', { name: 'baseline_da_produzione', query: ddl });
    if (r.stato >= 300) throw new Error('applicazione fallita (HTTP ' + r.stato + '): ' + JSON.stringify(r.dati).slice(0, 900));
    console.log('baseline applicata al collaudo (HTTP ' + r.stato + ')');
  }

  if (cmd === 'applica' || cmd === 'confronta') {
    const c = collaudo();
    const dColl = await descrivi(c.query);
    fs.writeFileSync(path.join(QUI, 'struttura-collaudo.json'), JSON.stringify(dColl, null, 1));
    const diff = differenze(ripulisci(dProd), ripulisci(dColl));
    const conta = (d) => Object.entries(d).filter(([, v]) => Array.isArray(v)).map(([k, v]) => k + ' ' + v.length).join(', ');
    console.log('produzione: ' + conta(dProd));
    console.log('collaudo:   ' + conta(dColl));
    if (!diff.length) console.log('CONFRONTO: IDENTICHE (a parte ciò che il collaudo ha in più per scelta: RLS automatica e posta_simulata)');
    else { console.log('CONFRONTO: ' + diff.length + ' DIFFERENZE'); diff.slice(0, 60).forEach((x) => console.log('  ' + x)); }
  }
}

main().catch((e) => { console.log('ERRORE: ' + e.message); process.exit(1); });
